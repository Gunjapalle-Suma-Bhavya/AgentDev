def create_task(task_id: str, project_name: str, idea: str) -> Dict[str, Any]:
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
    INSERT INTO tasks (task_id, project_name, idea, status, stage, progress, elapsed, logs_json, created_at, updated_at)
    VALUES (?, ?, ?, 'queued', 'Initializing Team...', 0, 0.0, '[]', ?, ?)
    """, (task_id, project_name, idea, now, now))
    conn.commit()
    conn.close()
    upsert_project(project_name, description=idea[:120], status="in_progress")
    return {
        "task_id": task_id,
        "project_name": project_name,
        "idea": idea,
        "status": "queued",
        "stage": "Initializing Team...",
        "progress": 0,
        "logs": [],
        "created_at": now
    }

def update_task(task_id: str, status: Optional[str] = None, stage: Optional[str] = None,
                progress: Optional[int] = None, elapsed: Optional[float] = None,
                new_log: Optional[str] = None, pid: Optional[int] = None):
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT logs_json FROM tasks WHERE task_id = ?", (task_id,))
    row = cursor.fetchone()
    if not row:
        conn.close()
        return

    logs = []
    try:
        logs = json.loads(row["logs_json"])
    except Exception:
        logs = []

    if new_log:
        logs.append(new_log)

    now = time.strftime("%Y-%m-%d %H:%M:%S")
    updates = ["updated_at = ?", "logs_json = ?"]
    params = [now, json.dumps(logs)]

    if status is not None:
        updates.append("status = ?")
        params.append(status)
    if stage is not None:
        updates.append("stage = ?")
        params.append(stage)
    if progress is not None:
        updates.append("progress = ?")
        params.append(progress)
    if elapsed is not None:
        updates.append("elapsed = ?")
        params.append(elapsed)
    if pid is not None:
        updates.append("process_pid = ?")
        params.append(pid)

    params.append(task_id)
    cursor.execute(f"UPDATE tasks SET {', '.join(updates)} WHERE task_id = ?", params)
    conn.commit()
    conn.close()

def get_task(task_id: str) -> Optional[Dict[str, Any]]:
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM tasks WHERE task_id = ?", (task_id,))
    row = cursor.fetchone()
    conn.close()
    if not row:
        return None
    d = dict(row)
    try:
        d["logs"] = json.loads(d.get("logs_json", "[]"))
    except Exception:
        d["logs"] = []
    return d

