def get_dashboard_stats() -> Dict[str, Any]:
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("SELECT COUNT(*) FROM projects")
    total_projects = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM projects WHERE status = 'completed'")
    completed_projects = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM tasks WHERE status = 'running'")
    active_tasks = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM tasks WHERE status = 'failed' OR status = 'error'")
    failed_tasks = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM agent_activities")
    total_agent_executions = cursor.fetchone()[0]

    total_files = 0
    total_bytes = 0
    if WORKSPACE_DIR.exists():
        for f in WORKSPACE_DIR.rglob("*"):
            if f.is_file() and not any(part.startswith(".") for part in f.parts):
                total_files += 1
                try:
                    total_bytes += f.stat().st_size
                except Exception:
                    pass

    conn.close()

    return {
        "total_projects": total_projects,
        "completed_projects": completed_projects,
        "active_tasks": active_tasks,
        "failed_tasks": failed_tasks,
        "total_agent_executions": total_agent_executions,
        "generated_files": total_files,
        "storage_used_kb": round(total_bytes / 1024, 1),
    }

def calculate_project_analytics(project_name: str) -> Dict[str, Any]:
    proj_path = (WORKSPACE_DIR / project_name).resolve()
    if not proj_path.exists() or not proj_path.is_dir():
        return {
            "project_name": project_name,
            "total_loc": 0,
            "file_count": 0,
            "languages": {},
            "file_metrics": [],
            "agent_distribution": {},
            "estimated_tokens": 0,
            "estimated_cost_usd": 0.0,
        }

    total_loc = 0
    total_chars = 0
    languages: Dict[str, int] = {}
    file_metrics = []

    for f in proj_path.rglob("*"):
        if f.is_file() and not any(part.startswith(".") for part in f.parts):
            ext = f.suffix.lstrip(".").lower() or "txt"
            rel = str(f.relative_to(proj_path)).replace("\\", "/")
            try:
                content = f.read_text(encoding="utf-8", errors="replace")
                lines = content.splitlines()
                loc = len(lines)
                chars = len(content)
                total_loc += loc
                total_chars += chars
                languages[ext] = languages.get(ext, 0) + loc
                file_metrics.append({
                    "file": rel,
                    "loc": loc,
                    "extension": ext,
                    "size_bytes": f.stat().st_size
                })
            except Exception:
                pass

    # Estimated tokens: ~4 chars per token for inputs, plus code generations
    estimated_tokens = int(total_chars / 3.8) + (total_loc * 8)
    estimated_cost_usd = round((estimated_tokens / 1000) * 0.008, 4)

    # Agent workload distribution
    agent_distribution = {
        "Alice (Product Manager)": 15,
        "Bob (System Architect)": 20,
        "Eve (Project Manager)": 15,
        "Alex (Software Engineer)": 35,
        "David (QA Engineer)": 15
    }

    return {
        "project_name": project_name,
        "total_loc": total_loc,
        "file_count": len(file_metrics),
        "languages": languages,
        "file_metrics": file_metrics,
        "agent_distribution": agent_distribution,
        "estimated_tokens": estimated_tokens,
        "estimated_cost_usd": estimated_cost_usd,
    }

