def create_approval(task_id: str, project_name: str, stage: str, agent_name: str,
                    artifact_type: str, artifact_title: str, artifact_content: str) -> int:
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
    INSERT INTO approvals (task_id, project_name, stage, agent_name, artifact_type, artifact_title, artifact_content, status, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, 'pending', ?)
    """, (task_id, project_name, stage, agent_name, artifact_type, artifact_title, artifact_content, now))
    approval_id = cursor.lastrowid
    conn.commit()
    conn.close()
    return approval_id

def resolve_approval(approval_id: int, status: str, feedback: str = "") -> bool:
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
    UPDATE approvals SET status = ?, feedback = ?, decided_at = ? WHERE id = ?
    """, (status, feedback, now, approval_id))
    affected = cursor.rowcount > 0
    conn.commit()
    conn.close()
    return affected

