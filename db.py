def get_dashboard_stats() -> Dict[str, Any]:
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("SELECT COUNT(*) FROM projects")
    total_projects = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM projects WHERE status = 'completed'")
    completed_projects = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM tasks WHERE status = 'running'")
    active_tasks = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM tasks WHERE status = 'failed' OR status = 'error'")
    failed_tasks = cursor.fetchone()[0]

    cursor.execute("SELECT COUNT(*) FROM agent_activities")
    total_agent_executions = cursor.fetchone()[0]

    # Calculate actual generated files count across workspace
    total_files = 0
    total_bytes = 0
    if WORKSPACE_DIR.exists():
        for f in WORKSPACE_DIR.rglob("*"):
            if f.is_file() and not any(part.startswith(".") for part in f.parts):
                total_files += 1
                try:
                    total_bytes += f.stat().st_size
                except Exception:
                    pass

    conn.close()

    return {
        "total_projects": total_projects,
        "completed_projects": completed_projects,
        "active_tasks": active_tasks,
        "failed_tasks": failed_tasks,
        "total_agent_executions": total_agent_executions,
        "generated_files": total_files,
        "storage_used_kb": round(total_bytes / 1024, 1),
    }

