"""
AgentDev Database Persistence Layer
Built with Python standard library sqlite3 for zero external dependencies, robust transactional storage,
and full persistence across server restarts.
"""

import os
import json
import sqlite3
import time
from pathlib import Path
from typing import Dict, List, Any, Optional

DB_FILE = Path(__file__).parent.resolve() / "agentdev.db"
WORKSPACE_DIR = Path(__file__).parent.resolve() / "workspace"

def get_connection() -> sqlite3.Connection:
    conn = sqlite3.connect(str(DB_FILE), check_same_thread=False)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    conn = get_connection()
    cursor = conn.cursor()

    # Projects Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS projects (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT UNIQUE NOT NULL,
        description TEXT,
        category TEXT DEFAULT 'Full-Stack',
        tech_stack TEXT DEFAULT '[]',
        status TEXT DEFAULT 'completed',
        file_count INTEGER DEFAULT 0,
        created_at TEXT,
        updated_at TEXT
    )
    """)

    # Tasks Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS tasks (
        task_id TEXT PRIMARY KEY,
        project_name TEXT NOT NULL,
        idea TEXT,
        status TEXT DEFAULT 'queued',
        stage TEXT DEFAULT 'Initializing Team...',
        progress INTEGER DEFAULT 0,
        elapsed REAL DEFAULT 0.0,
        logs_json TEXT DEFAULT '[]',
        process_pid INTEGER,
        created_at TEXT,
        updated_at TEXT
    )
    """)

    # Agent Activities Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS agent_activities (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        task_id TEXT,
        agent_role TEXT,
        agent_name TEXT,
        action TEXT,
        status TEXT,
        message TEXT,
        duration_sec REAL DEFAULT 0.0,
        timestamp TEXT
    )
    """)

    # Human Approvals Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS approvals (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        task_id TEXT,
        project_name TEXT,
        stage TEXT,
        agent_name TEXT,
        artifact_type TEXT,
        artifact_title TEXT,
        artifact_content TEXT,
        status TEXT DEFAULT 'pending',
        feedback TEXT,
        created_at TEXT,
        decided_at TEXT
    )
    """)

    # QA Reports Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS qa_reports (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        project_name TEXT NOT NULL,
        task_id TEXT,
        total_tests INTEGER DEFAULT 0,
        passed INTEGER DEFAULT 0,
        failed INTEGER DEFAULT 0,
        skipped INTEGER DEFAULT 0,
        syntax_errors INTEGER DEFAULT 0,
        quality_score INTEGER DEFAULT 100,
        summary TEXT,
        details TEXT DEFAULT '[]',
        created_at TEXT
    )
    """)

    # API Request Logs Table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS api_logs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        endpoint TEXT,
        method TEXT,
        status_code INTEGER,
        duration_ms REAL,
        timestamp TEXT
    )
    """)

    conn.commit()
    conn.close()
    sync_workspace_projects()

def sync_workspace_projects():
    """Scan workspace directory on startup and synchronize with projects table."""
    if not WORKSPACE_DIR.exists():
        return

    conn = get_connection()
    cursor = conn.cursor()

    for p in WORKSPACE_DIR.iterdir():
        if p.is_dir() and not p.name.startswith("."):
            files = [f for f in p.rglob("*") if f.is_file() and not any(part.startswith(".") for part in f.parts)]
            mod_time = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(p.stat().st_mtime))
            
            # Check if project already exists
            cursor.execute("SELECT id FROM projects WHERE name = ?", (p.name,))
            row = cursor.fetchone()
            if row is None:
                cursor.execute("""
                INSERT INTO projects (name, description, category, tech_stack, status, file_count, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    p.name,
                    f"Autonomous software repository generated by AgentDev multi-agent team.",
                    "Python / Full-Stack",
                    json.dumps(["Python", "MetaGPT", "FastAPI"]),
                    "completed",
                    len(files),
                    mod_time,
                    mod_time
                ))
            else:
                cursor.execute("""
                UPDATE projects SET file_count = ?, updated_at = ? WHERE name = ?
                """, (len(files), mod_time, p.name))

    conn.commit()
    conn.close()

