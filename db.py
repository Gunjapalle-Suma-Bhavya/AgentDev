def get_all_projects() -> List[Dict[str, Any]]:
    sync_workspace_projects()
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM projects ORDER BY updated_at DESC")
    rows = cursor.fetchall()
    conn.close()
    
    projects = []
    for r in rows:
        p = dict(r)
        try:
            p["tech_stack"] = json.loads(p.get("tech_stack", "[]"))
        except Exception:
            p["tech_stack"] = []
        projects.append(p)
    return projects

def upsert_project(name: str, description: str = "", category: str = "Web App", tech_stack: list = None, status: str = "in_progress"):
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    tech_json = json.dumps(tech_stack or ["Python", "FastAPI"])
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT id FROM projects WHERE name = ?", (name,))
    row = cursor.fetchone()
    if row:
        cursor.execute("""
        UPDATE projects SET description = ?, category = ?, tech_stack = ?, status = ?, updated_at = ?
        WHERE name = ?
        """, (description, category, tech_json, status, now, name))
    else:
        cursor.execute("""
        INSERT INTO projects (name, description, category, tech_stack, status, file_count, created_at, updated_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """, (name, description, category, tech_json, status, 0, now, now))
    conn.commit()
    conn.close()

