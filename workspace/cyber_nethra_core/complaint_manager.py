import uuid
import time
from typing import Dict, Optional
from pydantic import BaseModel

class IncidentReport(BaseModel):
    reference_id: str
    category: str
    description: str
    complainant_name: str
    contact_email: str
    evidence_filename: Optional[str] = None
    status: str = "Submitted"
    timestamp: str

class ComplaintManager:
    def __init__(self):
        self._incidents: Dict[str, IncidentReport] = {}

    def create_incident(self, category: str, description: str, name: str, email: str, evidence: Optional[str] = None) -> IncidentReport:
        ref_id = f"CN-{time.strftime('%Y%m%d')}-{uuid.uuid4().hex[:6].upper()}"
        report = IncidentReport(
            reference_id=ref_id,
            category=category,
            description=description,
            complainant_name=name,
            contact_email=email,
            evidence_filename=evidence,
            status="Under Review",
            timestamp=time.strftime("%Y-%m-%d %H:%M:%S")
        )
        self._incidents[ref_id] = report
        return report

    def get_incident(self, reference_id: str) -> Optional[IncidentReport]:
        return self._incidents.get(reference_id)
