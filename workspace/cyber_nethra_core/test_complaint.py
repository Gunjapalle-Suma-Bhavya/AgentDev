import unittest
import sys
from pathlib import Path

# Add current folder to path
sys.path.insert(0, str(Path(__file__).parent.resolve()))

from complaint_manager import ComplaintManager
from forensic_analyzer import ForensicAnalyzer

class TestCyberNethraCore(unittest.TestCase):
    def test_incident_creation(self):
        mgr = ComplaintManager()
        rep = mgr.create_incident(
            category="Financial Fraud",
            description="Unauthorized phishing withdrawal via banking portal",
            name="John Doe",
            email="john@example.com"
        )
        self.assertTrue(rep.reference_id.startswith("CN-"))
        self.assertEqual(rep.status, "Under Review")
        self.assertIsNotNone(mgr.get_incident(rep.reference_id))

    def test_forensic_hasher(self):
        analyzer = ForensicAnalyzer()
        res = analyzer.analyze("evidence_sample.mp4", b"binary content payload")
        self.assertEqual(len(res.sha256_hash), 64)
        self.assertEqual(res.integrity_status, "Verified Valid")
        self.assertGreaterEqual(res.deepfake_probability, 0.0)

if __name__ == "__main__":
    unittest.main()
